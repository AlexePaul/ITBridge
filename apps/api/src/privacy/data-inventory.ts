import type { ColumnClassification, EntityInventory, PersonalColumn } from './data-inventory.types';

/**
 * Every column the platform stores, and what it is — E07 S1.
 *
 * The epic asks for one table naming each personal-data field, why it is held, on what legal basis,
 * for how long and who can see it. Its acceptance adds the part that makes this code rather than
 * prose: **a new column holding personal data cannot reach production without appearing here.**
 * `data-inventory.spec.ts` enforces exactly that — it reads TypeORM's own metadata and fails on any
 * column with no entry, and on any entry whose column is gone.
 *
 * So this file classifies *every* column, not only the personal ones. A field is either personal
 * data with the five answers filled in, or it is not, with a named reason from a short list. There
 * is no third state, because the third state is how a phone number ends up unclassified.
 *
 * **The privacy note is written from here, not beside it** (E22 S2). `docs/inventar-date.md` is
 * rendered from this file and checked for drift in the same spec, so the copy a family eventually
 * reads cannot be the one that fell behind.
 *
 * Two rules that decide most of the rows below, worth stating once:
 *
 * - **What makes a column personal is that it carries a fact about the person, not that it spells
 *   their name.** An invoice amount is not a number in the abstract; it is what *this* family owes,
 *   and marking money "not personal" because it holds no name is the mistake this file exists to
 *   prevent — GDPR's definition is information *relating to* an identifiable person, not
 *   information that identifies one. What stays outside is the row's own machinery: surrogate keys,
 *   write timestamps, internal plumbing. Those describe the row, not the person.
 * - **Deletion follows the row, not the column.** What goes when a family goes is decided per table
 *   by `linkedVia`, so a `createdAt` on a child's row is deleted with it whether or not it counts
 *   as personal data here. The two answer different questions: this file answers "what belongs in
 *   the privacy note", `linkedVia` answers "what disappears".
 * - **The school's own things are not personal data.** Rooms, timetables, holiday periods, mail
 *   templates, the branch address and phone: those are the school, not a data subject.
 */
