export function personalColumns(): { entity: string; column: string; classification: PersonalColumn }[] {
    const out: { entity: string; column: string; classification: PersonalColumn }[] = [];
    for (const [entity, inventory] of Object.entries(DATA_INVENTORY)) {
        for (const [column, classification] of Object.entries(inventory.columns)) {
            if (isPersonal(classification)) out.push({ entity, column, classification });
        }
    }
    return out;
}

export function isPersonal(classification: ColumnClassification): classification is PersonalColumn {
    return classification.personal;
}
